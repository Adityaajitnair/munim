# ---------------------------------------------------------------------------
# Data models - "what a valid ledger row looks like"
# ---------------------------------------------------------------------------

class OrderIn(BaseModel):
    """Order coming from the LangGraph pipeline (all core fields required -
    the pipeline only produces these when it UNDERSTOOD the speech)."""

    supplier: str = Field(..., description="Brand/company, e.g. 'amul'")
    item: str = Field(..., description="Product, e.g. 'milk packet'")
    quantity: float = Field(..., gt=0, description="How many")
    unit: Optional[str] = Field(None, description="packet / carton / kg ...")
    total_amount: Optional[float] = Field(None, ge=0, description="Rupees")
    item_guessed: bool = Field(False, description="True if item came from the lookup table")


class ClarificationIn(BaseModel):
    """A 'stuck' order (Option A: we RECORD these, never lose them).

    The pipeline may have understood SOME of the fields (e.g. it knows the
    item is milk but nobody said the supplier) - those partial fields are
    kept so the merchant's later answer just fills the gaps.
    """

    question: str = Field(..., description="What we must ask the merchant")
    transcript: Optional[str] = Field(None, description="What Sarvam heard")
    supplier: Optional[str] = None
    item: Optional[str] = None
    quantity: Optional[float] = None
    unit: Optional[str] = None
    total_amount: Optional[float] = None
    item_guessed: bool = False


class AnswerIn(BaseModel):
    """The merchant's answer - only the fields they are filling in.

    Same validation rules as OrderIn, so a clarification can never smuggle
    in a negative quantity or amount.
    """

    supplier: Optional[str] = None
    item: Optional[str] = None
    quantity: Optional[float] = Field(None, gt=0)
    unit: Optional[str] = None
    total_amount: Optional[float] = Field(None, ge=0)


class VoiceIn(BaseModel):
    """Which recorded clip to pipe through the (simulated mic) pipeline."""

    audio_file: str = Field(..., description="Path relative to project, e.g. samples/amul1.mp3")


class LedgerEntry(BaseModel):
    """One row of the ledger - either a pending order or a clarification."""

    id: str
    status: str                  # needs_clarification | pending | (later: confirmed/executed)
    supplier: Optional[str] = None
    item: Optional[str] = None
    quantity: Optional[float] = None
    unit: Optional[str] = None
    total_amount: Optional[float] = None
    item_guessed: bool = False
    question: Optional[str] = None        # only on needs_clarification rows
    missing_fields: List[str] = []        # what the merchant still has to tell us
    clarified: bool = False               # True once a stuck order was completed by an answer
    transcript: Optional[str] = None      # what Sarvam heard (audit trail)
    created_at: float
    answered_at: Optional[float] = None   # set when the merchant answered


# ---------------------------------------------------------------------------
# "Database" - a list in memory for this MVP step
# ---------------------------------------------------------------------------

ledger: List[LedgerEntry] = []
SAMPLES_DIR = Path("samples")


# A row is only a real order once ALL of these are known.
REQUIRED_FIELDS = ("supplier", "item", "quantity")
ANSWERABLE_FIELDS = ("supplier", "item", "quantity", "unit", "total_amount")


def _create_entry(**kwargs) -> LedgerEntry:
    """Shared helper: build a ledger row with a fresh id + timestamp."""
    entry = LedgerEntry(
        id=uuid.uuid4().hex[:6],
        created_at=time.time(),
        **kwargs,
    )
    if entry.status == "needs_clarification":
        entry.missing_fields = _missing_fields(entry)
    ledger.append(entry)
    return entry


def _missing_fields(entry: LedgerEntry) -> List[str]:
    """Which required fields are still missing on this row?"""
    return [f for f in REQUIRED_FIELDS if not getattr(entry, f)]


def _next_question(entry: LedgerEntry, still_missing: List[str]) -> str:
    """Build the follow-up question for whatever is still missing."""
    names = " and ".join(still_missing)
    known = []
    if entry.quantity:
        known.append(f"{entry.quantity:g}")
    if entry.item:
        known.append(entry.item)
    if entry.supplier:
        known.append(f"from {entry.supplier}")
    context = f" ({' '.join(known)})" if known else ""
    return f"Noted{context}. What {names} should I fill in?"


