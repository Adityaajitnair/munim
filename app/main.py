"""
app/main.py - MunimAI's digital ledger server (Steps 3 + 4).

What this is:
    The web server / ledger that the voice pipeline feeds into.

Endpoints:
    POST /orders              -> add a finished order (status: pending)
    GET  /orders              -> the whole ledger
    GET  /orders/{id}         -> one order
    POST /orders/voice        -> run the FULL voice pipeline on a sample clip
                                 and let the ledger record the outcome
    POST /clarifications      -> record a "stuck" order (needs_clarification)
    POST /clarifications/{id}/answer -> merchant answers; row fills in and
                                        becomes a pending order if complete
    GET  /metrics             -> benchmark report from test_sentences.py
    GET  /calls               -> recent API calls (dashboard panel)
    GET  /dashboard           -> the live merchant dashboard (HTML)
    GET  /docs                -> Swagger API explorer (auto-generated by FastAPI)

Status lifecycle (the roadmap's state machine - makes the
"nothing executes without confirmation" claim real):
    needs_clarification -> pending -> confirmed -> executed (later steps)

Stuck-order flow (this file's core idea):
    1. Pipeline can't finish an order  -> row saved as needs_clarification,
       with whatever WAS understood + a question + `missing_fields`.
    2. Merchant answers (dashboard or POST /clarifications/{id}/answer).
    3. Answer is merged into the SAME row. Still gaps? -> next question.
       Complete? -> row flips to `pending`, flagged `clarified=True`, and is
       now a real order in the ledger (nothing is ever lost or duplicated).

NOTE: Paytm / Soundbox integration is SIMULATED in this prototype - the
voice input here is a pre-recorded sample file, not a live microphone yet.

Run it:
    .\\venv\\Scripts\\uvicorn.exe app.main:app --port 8000
"""

