@app.post("/orders", response_model=LedgerEntry, status_code=201)
def add_order(order: OrderIn) -> LedgerEntry:
    """
    Add one finished order to the ledger (called by the LangGraph pipeline
    or typed by hand in Swagger). Starts as 'pending' - nothing executes
    before confirmation (that part comes in a later step).
    """
    return _create_entry(
        status="pending",
        supplier=order.supplier,
        item=order.item,
        quantity=order.quantity,
        unit=order.unit,
        total_amount=order.total_amount,
        item_guessed=order.item_guessed,
    )


@app.post("/clarifications", response_model=LedgerEntry, status_code=201)
def add_clarification(clar: ClarificationIn) -> LedgerEntry:
    """
    Record a 'stuck' order (Option A design decision). We keep everything
    the pipeline DID understand, plus the question for the merchant.
    """
    return _create_entry(
        status="needs_clarification",
        question=clar.question,
        transcript=clar.transcript,
        supplier=clar.supplier,
        item=clar.item,
        quantity=clar.quantity,
        unit=clar.unit,
        total_amount=clar.total_amount,
        item_guessed=clar.item_guessed,
    )


@app.post("/clarifications/{entry_id}/answer", response_model=LedgerEntry)
def answer_clarification(entry_id: str, answer: AnswerIn) -> LedgerEntry:
    """
    The merchant fills the gaps. Answers are merged into the SAME row:
      - still something missing -> row stays needs_clarification, NEXT question
      - everything known        -> row becomes a normal `pending` order
                                   (clarified=True, so the audit trail shows
                                   it started life as a stuck order)
    """
    entry = _find(entry_id)

    # Only stuck rows can be answered - otherwise this endpoint could
    # silently overwrite a finished order.
    if entry.status != "needs_clarification":
        raise HTTPException(
            status_code=409,
            detail=f"Entry '{entry_id}' is '{entry.status}', not waiting for clarification.",
        )

    # Merge only the fields the merchant actually provided (blank = skipped).
    provided = {}
    for field in ANSWERABLE_FIELDS:
        value = getattr(answer, field)
        if isinstance(value, str):
            value = value.strip().lower() if field in ("supplier", "item", "unit") else value.strip()
        if value not in (None, ""):
            provided[field] = value
    if not provided:
        raise HTTPException(status_code=422, detail="Answer is empty - fill in at least one field.")

    for field, value in provided.items():
        setattr(entry, field, value)
    entry.answered_at = time.time()

    still_missing = _missing_fields(entry)
    entry.missing_fields = still_missing
    if still_missing:
        entry.question = _next_question(entry, still_missing)
    else:
        entry.status = "pending"     # complete enough to be a real order
        entry.question = None
        entry.clarified = True
    return entry


def _find(entry_id: str) -> LedgerEntry:
    for o in ledger:
        if o.id == entry_id:
            return o
    raise HTTPException(status_code=404, detail=f"No ledger entry with id '{entry_id}'")


@app.get("/orders", response_model=List[LedgerEntry])
def list_orders() -> List[LedgerEntry]:
    """The whole ledger, oldest first (orders AND clarifications)."""
    return ledger


@app.get("/orders/{order_id}", response_model=LedgerEntry)
def get_order(order_id: str) -> LedgerEntry:
    """Look up one entry by id (404 with a clear message if unknown)."""
    return _find(order_id)


