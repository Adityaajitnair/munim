@app.post("/orders/voice", response_model=LedgerEntry, status_code=201)
def order_from_voice(voice: VoiceIn) -> LedgerEntry:
    """
    Run the FULL pipeline on a recorded clip and record the outcome:
      - understood   -> pending order row
      - stuck        -> needs_clarification row (Option A: never lost)

    The 'mic' is simulated for now: we read a file instead of a live mic.
    """
    # Lazy import: keeps server boot fast, isolates AI-stack failures here.
    from pipeline.graph import run_pipeline

    # Only clips inside samples/ may be run - never arbitrary files on disk.
    audio_path = SAMPLES_DIR / Path(voice.audio_file).name
    if not audio_path.is_file():
        raise HTTPException(status_code=422, detail=f"Audio file not found: '{voice.audio_file}'")
    try:
        state = run_pipeline(str(audio_path))
    except FileNotFoundError:
        raise HTTPException(status_code=422, detail=f"Audio file not found: '{voice.audio_file}'")
    except RuntimeError as e:
        # Friendly pipeline errors (bad key, bad audio, rate limit...) -> 502
        raise HTTPException(status_code=502, detail=str(e))
    except Exception as e:                                  # noqa: BLE001
        raise HTTPException(status_code=502, detail=f"Pipeline crashed: {type(e).__name__}: {e}")

    transcript = state.get("transcript", "")

    if state.get("final_order") and state["final_order"].get("quantity"):
        order = state["final_order"]
        return _create_entry(
            status="pending",
            supplier=order["supplier"],
            item=order["item"],
            quantity=order["quantity"],
            unit=order["unit"],
            total_amount=order["total_amount"],
            item_guessed=bool(order.get("item_guessed", False)),
            transcript=transcript,
        )

    # Could NOT understand enough - record the question, never lose it.
    return _create_entry(
        status="needs_clarification",
        question=state.get("clarification_question") or "Please repeat the order.",
        transcript=transcript,
        supplier=state.get("supplier"),
        item=state.get("item"),
        quantity=state.get("quantity"),
        unit=state.get("unit"),
        total_amount=state.get("total_amount"),
        item_guessed=bool(state.get("item_guessed", False)),
    )


